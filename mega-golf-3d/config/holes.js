// 每日挑战洞：按日期 seed 选 1 洞（用 24 洞几何，可后续给变体；结构保持）
export function dailyHole(dateSeed) {
  const s = (dateSeed >>> 0) || 1;
  const idx = (s % HOLES.length + HOLES.length) % HOLES.length;
  return { index: idx, hole: HOLES[idx] };
}

export function totalPar() {
  return HOLES.reduce((s, h) => s + h.par, 0);
}
