def main() -> int:
    ja = json.loads(JA.read_text())
    out = {}
    missing = []
    for ch, info in ja.items():
        lines = []
        for l in info["lines"]:
            if "section" in l:
                sec = l["section"]
                zh = SECTIONS.get(sec)
                if zh is None:
                    missing.append(f"{ch} section: {sec}")
                    zh = sec
                lines.append({"section": sec, "sectionZh": zh})
            elif "who" in l:
                who_zh = SPEAKERS.get(l["who"])
                if who_zh is None:
                    missing.append(f"{ch} who: {l['who']}")
                    who_zh = l["who"]
                zh = ZH.get(ch, {}).get(l["text"])
                if not zh:
                    missing.append(f"{ch} text: {l['who']}「{l['text']}」")
                    zh = ""
                lines.append({"who": l["who"], "whoZh": who_zh,
                              "text": l["text"], "textZh": zh})
            else:
                zh = ZH.get(ch, {}).get(l["text"])
                if not zh:
                    missing.append(f"{ch} narr: {l['text']}")
                    zh = ""
                lines.append({"text": l["text"], "textZh": zh})
        out[ch] = {"title": info["title"], "titleZh": TITLES.get(ch, ""), "lines": lines}

    if missing:
        print("缺少翻译：")
        for m in missing:
            print("  ", m)
        raise SystemExit(1)

    ZH.write_text(json.dumps(out, ensure_ascii=False, indent=1))
    SPEAKER_MAP.write_text(json.dumps(SPEAKERS, ensure_ascii=False, indent=1))
    print(f"wrote {ZH.relative_to(ROOT)} ({ZH.stat().st_size} bytes)")
    print(f"wrote {SPEAKER_MAP.relative_to(ROOT)} ({SPEAKER_MAP.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
